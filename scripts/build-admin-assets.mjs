/**
 * Prepares everything /admin needs that isn't hand-written:
 *
 *  1. decap-cms.js      — the pinned CMS bundle, copied out of node_modules
 *  2. preview.css       — the real site stylesheet, so the CMS preview looks
 *                         like the actual site instead of an approximation
 *  3. preview-content.js — a snapshot of the content the homepage preview needs
 *                         but doesn't own (about, skills, contact, projects),
 *                         so the preview can show the whole page in context
 *
 * Runs before every build and before `npm run dev`.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { readdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { parse } from 'yaml'

const require = createRequire(import.meta.url)
const admin = new URL('../public/admin/', import.meta.url)
const styles = new URL('../src/styles/', import.meta.url)
const content = new URL('../content/', import.meta.url)

mkdirSync(admin, { recursive: true })

/* 1 — CMS bundle */
copyFileSync(require.resolve('decap-cms/dist/decap-cms.js'), new URL('decap-cms.js', admin))
const { version } = require('decap-cms/package.json')

/* 2 — site stylesheet, concatenated in the same order main.jsx imports it */
const css = ['tokens.css', 'global.css', 'components.css']
  .map((file) => `/* ---- ${file} ---- */\n${readFileSync(new URL(file, styles), 'utf8')}`)
  .join('\n\n')
writeFileSync(
  new URL('preview.css', admin),
  `/* Generated by scripts/build-admin-assets.mjs from src/styles/. Do not edit. */\n\n${css}\n`
)

/* 3 — content snapshot for sections the homepage preview doesn't own */
const yml = (file) => parse(readFileSync(new URL(file, content), 'utf8'))
const projects = readdirSync(new URL('projects/', content))
  .filter((f) => f.endsWith('.yml'))
  .map((f) => ({ slug: f.replace(/\.yml$/, ''), ...yml(`projects/${f}`) }))
  .sort((a, b) => (a.order ?? 999) - (b.order ?? 999))

const snapshot = {
  general: yml('general.yml'),
  about: yml('about.yml'),
  experience: yml('experience.yml'),
  skills: yml('skills.yml'),
  contact: yml('contact.yml'),
  projects
}
writeFileSync(
  new URL('preview-content.js', admin),
  `/* Generated by scripts/build-admin-assets.mjs. Do not edit. */\n` +
    `window.PORTFOLIO_CONTENT = ${JSON.stringify(snapshot, null, 2)}\n`
)

console.log(
  `Admin assets ready — Decap ${version}, preview.css (${Math.round(css.length / 1024)} KB), ` +
    `snapshot of ${projects.length} projects`
)
